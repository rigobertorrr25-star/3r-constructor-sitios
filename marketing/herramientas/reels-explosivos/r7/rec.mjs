import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const OUT = process.argv[2];
const FD = OUT + '/frames';
fs.mkdirSync(FD, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 432, height: 768 }, deviceScaleFactor: 2.5, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const frames = [];
let n = 0, shooting = false, loop = null;
const shoot = async () => { while (shooting) { const name = FD + '/' + String(n++).padStart(5, '0') + '.jpg'; const ts = Date.now() / 1000; try { await p.screenshot({ path: name, type: 'jpeg', quality: 88 }); frames.push([name, ts]); } catch {} } };
const marks = {};
const mark = (k) => { marks[k] = Date.now() / 1000; };
await p.goto('http://localhost:8098/', { waitUntil: 'networkidle' });
await p.waitForTimeout(500);
shooting = true; loop = shoot();
await p.waitForTimeout(300);
mark('hero'); await p.waitForTimeout(1700);
await p.getByText('Ver el menú').first().tap(); await p.waitForTimeout(1200);
mark('menu');
await p.locator('button:has-text("Aperitivos")').first().tap(); await p.waitForTimeout(1300);
mark('cat');
const adds = p.locator('button:has-text("Agregar"):visible');
await adds.nth(0).tap(); await p.waitForTimeout(800);
mark('add1');
await p.locator('button:has-text("Bar & Coctelería")').first().tap(); await p.waitForTimeout(1300);
mark('bar');
await adds.nth(0).tap(); await p.waitForTimeout(700);
await adds.nth(1).tap(); await p.waitForTimeout(900);
mark('add2');
await p.locator('button:has-text("Pedido")').first().tap(); await p.waitForTimeout(2400);
mark('cart');
await p.waitForTimeout(600);
shooting = false; await loop;
const t00 = frames[0][1];
let list = '';
for (let i = 0; i < frames.length; i++) {
  const d = i + 1 < frames.length ? frames[i + 1][1] - frames[i][1] : 0.5;
  list += `file '${frames[i][0]}'\nduration ${d.toFixed(4)}\n`;
}
list += `file '${frames[frames.length - 1][0]}'\n`;
fs.writeFileSync(OUT + '/frames.txt', list);
console.log('frames', frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - t00).toFixed(2)]))));
await ctx.close(); await b.close();
