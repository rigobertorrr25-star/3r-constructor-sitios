import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const OUT = process.argv[2];
const FD = OUT + '/frames';
fs.mkdirSync(FD, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 432, height: 768 }, deviceScaleFactor: 2.5, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const frames = [], taps = [], marks = {};
let n = 0, shooting = false, loop = null;
const shoot = async () => { while (shooting) { const name = FD + '/' + String(n++).padStart(5, '0') + '.jpg'; const ts = Date.now() / 1000; try { await p.screenshot({ path: name, type: 'jpeg', quality: 88 }); frames.push([name, ts]); } catch {} } };
const mark = (k) => { marks[k] = Date.now() / 1000; };
const hide = () => p.addStyleTag({ content: 'nextjs-portal{display:none!important}' }).catch(() => {});
const tap = async (loc, wait = 600) => {
  await loc.scrollIntoViewIfNeeded().catch(() => {});
  const bb = await loc.boundingBox();
  const x = bb.x + bb.width / 2, y = bb.y + bb.height / 2;
  taps.push({ t: Date.now() / 1000, x: x * 2.5, y: y * 2.5 });
  await p.touchscreen.tap(x, y);
  await p.waitForTimeout(wait);
};
await p.goto('http://localhost:3200/', { waitUntil: 'networkidle' });
await hide(); await p.waitForTimeout(400);
shooting = true; loop = shoot();
await p.waitForTimeout(500);
mark('login');
await tap(p.getByText('Camilo').first(), 700);
await hide();
for (const d of '3691') await tap(p.getByRole('button', { name: d, exact: true }), 220);
await tap(p.getByRole('button', { name: 'Entrar' }), 2200);
await hide();
mark('map'); await p.waitForTimeout(600);
await tap(p.locator('text=/^3$/').first(), 900);
await tap(p.getByRole('button', { name: 'Abrir mesa' }), 2000);
await hide();
mark('order');
await tap(p.locator('button:has-text("Mojito")').first(), 450);
await tap(p.locator('button:has-text("Mojito")').first(), 450);
await tap(p.locator('button:has-text("Piña Colada")').first(), 500);
await tap(p.locator('button:has-text("Cerveza")').first(), 700);
await tap(p.locator('button:has-text("Club Colombia")').first(), 450);
await tap(p.locator('button:has-text("Club Colombia")').first(), 700);
mark('send');
await tap(p.getByRole('button', { name: /Enviar a/ }), 2200);
mark('end');
await p.waitForTimeout(500);
shooting = false; await loop;
const t00 = frames[0][1];
let list = '';
for (let i = 0; i < frames.length; i++) {
  const d = i + 1 < frames.length ? frames[i + 1][1] - frames[i][1] : 0.5;
  list += `file '${frames[i][0]}'\nduration ${d.toFixed(4)}\n`;
}
list += `file '${frames[frames.length - 1][0]}'\n`;
fs.writeFileSync(OUT + '/frames.txt', list);
fs.writeFileSync(OUT + '/taps.json', JSON.stringify(taps.map((q) => ({ ...q, t: +(q.t - t00).toFixed(2) }))));
console.log('frames', frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - t00).toFixed(2)]))));
await ctx.close(); await b.close();
