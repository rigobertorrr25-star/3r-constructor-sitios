import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const OUT = process.argv[2];
const FD = OUT + '/' + process.argv[3];
fs.mkdirSync(FD, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 432, height: 768 }, deviceScaleFactor: 2.5, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const cdp = await ctx.newCDPSession(p);
const frames = [];
let n = 0;
let shooting = false; let loop = null;
const shoot = async () => { while (shooting) { const name = FD + '/' + String(n++).padStart(5, '0') + '.jpg'; const ts = Date.now() / 1000; try { await p.screenshot({ path: name, type: 'jpeg', quality: 88 }); frames.push([name, ts]); } catch {} } };
const marks = {};
const mark = (k) => { marks[k] = Date.now() / 1000; };
const closeOv = async () => { await p.waitForTimeout(250); const o = p.locator('div.fixed.inset-0.backdrop-blur-sm button'); if (await o.count()) { await o.first().click({ force: true }); await p.waitForTimeout(450); } };
await p.goto('http://localhost:8095/', { waitUntil: 'networkidle' });
await p.waitForTimeout(600);
const ov = p.locator('div.fixed.inset-0 button');
for (let i = 0; i < 10 && !(await ov.count()); i++) await p.waitForTimeout(300);
if (await ov.count()) await ov.first().click({ force: true });
await p.waitForTimeout(500);
await p.evaluate(() => window.scrollTo(0, 0));
shooting = true; loop = shoot();
await p.waitForTimeout(400);
mark('hero'); await p.waitForTimeout(1900);
await p.getByText('Ver el menú').first().click(); await p.waitForTimeout(900);
const card = p.locator('button:has-text("Fettuccine")').first();
await card.scrollIntoViewIfNeeded(); await p.evaluate(() => window.scrollBy(0, -120)); await p.waitForTimeout(700);
await closeOv(); mark('pick'); await card.tap(); await p.waitForTimeout(700);
await p.locator('button:has-text("Agregar")').first().tap(); await p.waitForTimeout(900);
const pen = p.locator('button:has-text("Penne")').nth(1);
await pen.scrollIntoViewIfNeeded(); await p.evaluate(() => window.scrollBy(0, -120)); await p.waitForTimeout(500);
await closeOv(); mark('add2'); await pen.tap(); await p.waitForTimeout(500);
await p.locator('button:has-text("Agregar")').nth(1).tap(); await p.waitForTimeout(900);
mark('cart'); await p.getByRole('button', { name: /Carrito/ }).first().tap(); await p.waitForTimeout(2800);
mark('end');
shooting = false; await loop;
await p.waitForTimeout(300);
const t00 = frames[0][1];
let list = '';
for (let i = 0; i < frames.length; i++) {
  const d = i + 1 < frames.length ? frames[i + 1][1] - frames[i][1] : 0.5;
  list += `file '${frames[i][0]}'\nduration ${d.toFixed(4)}\n`;
}
list += `file '${frames[frames.length - 1][0]}'\n`;
fs.writeFileSync(OUT + '/frames.txt', list);
const rel = Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - t00).toFixed(2)]));
console.log('frames', frames.length, 'span', (frames[frames.length - 1][1] - t00).toFixed(2), JSON.stringify(rel));
await ctx.close(); await b.close();
