import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const OUT = process.argv[2];
const FD = OUT + '/frames';
fs.mkdirSync(FD, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 432, height: 768 }, deviceScaleFactor: 2.5, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const frames = [];
let n = 0, shooting = false, loop = null;
const shoot = async () => { while (shooting) { const name = FD + '/' + String(n++).padStart(5, '0') + '.jpg'; const ts = Date.now() / 1000; try { await p.screenshot({ path: name, type: 'jpeg', quality: 88 }); frames.push([name, ts]); } catch {} } };
const marks = {};
const mark = (k) => { marks[k] = Date.now() / 1000; };
await p.goto('http://localhost:8096/caprichos-tienda/', { waitUntil: 'networkidle' });
await p.getByText('ACEPTAR TODAS').click().catch(() => {});
await p.waitForTimeout(500);
shooting = true; loop = shoot();
await p.waitForTimeout(300);
mark('hero'); await p.waitForTimeout(1800);
await p.getByText('Ver catálogo').first().tap(); await p.waitForTimeout(900);
mark('catalog');
await p.mouse.wheel(0, 600); await p.waitForTimeout(900);
await p.mouse.wheel(0, 500); await p.waitForTimeout(900);
const prod = p.locator('img[src*="top-rojo-halter"]').first();
await prod.scrollIntoViewIfNeeded(); await p.waitForTimeout(500);
mark('tap'); await prod.tap(); await p.waitForTimeout(1500);
mark('product');
await p.locator('button:has-text("Añadir")').first().click({ force: true }); await p.waitForTimeout(1500);
mark('added');
const cart = p.locator('header button').last();
await cart.click({ force: true }); await p.waitForTimeout(2200);
mark('cart');
await p.waitForTimeout(800);
shooting = false; await loop;
const t00 = frames[0][1];
let list = '';
for (let i = 0; i < frames.length; i++) {
  const d = i + 1 < frames.length ? frames[i + 1][1] - frames[i][1] : 0.5;
  list += `file '${frames[i][0]}'\nduration ${d.toFixed(4)}\n`;
}
list += `file '${frames[frames.length - 1][0]}'\n`;
fs.writeFileSync(OUT + '/frames.txt', list);
console.log('frames', frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - t00).toFixed(2)]))));
await ctx.close(); await b.close();
